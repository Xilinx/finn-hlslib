#include "input_gen_top.hpp"
#include "input_gen.hpp"

void input_gen_top(
	hls::stream<val_t> &src,
	hls::stream<flit_t<val_t>> &dst
) {
#pragma HLS interface ap_ctrl_none port=return
#pragma HLS aggregate variable=dst compact=bit
	using namespace top;
	constexpr unsigned  OH = (H-KH)/SH + 1;
	constexpr unsigned  OW = (W-KW)/SW + 1;
	// Pooling nest as generated by FINN's Pool_hls: oh, ow, cf, kh, kw
	input_gen<2, H*W*CF, OH, SH*W*CF, OW, SW*CF, CF, 1, KH, W*CF, KW, CF>(src, dst);
}
